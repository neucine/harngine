import type { ApprovalPolicy } from './interaction.js';
import type { Identity } from './types.js';
import type { ObjectiveRevision } from './types.js';
import type { Reason } from './types.js';
import type { RequestId } from './types.js';
import type { Json, Schema } from './types.js';
import type { Guardrail } from './guardrail.js';
import type { ModelItem } from './model.js';
import type { ToolCapabilities } from './definition.js';
export type { ToolCapabilities } from './definition.js';

export type Outcome<O extends Json = Json> =
  | { status: 'success'; value: O }
  | { status: 'failure'; effect: 'none' | 'partial' | 'occurred'; reason: Reason }
  | { status: 'unknown'; reason: Reason };
export type ReconciliationResult<O extends Json = Json> =
  | { readonly status: 'success'; readonly value: O }
  | { readonly status: 'failure'; readonly effect: 'partial' | 'occurred'; readonly reason: Reason }
  | { readonly status: 'not-applied' | 'unknown'; readonly reason: Reason };
export interface Tool<I extends Json = Json, O extends Json = Json> extends Identity {
  readonly artifactDigest: string;
  readonly description?: string;
  readonly input: Schema<I>;
  readonly output: Schema<O>;
  readonly effect: 'read' | 'write';
  readonly capabilities?: ToolCapabilities;
  readonly approval?: ApprovalPolicy;
  /** Internal execution policy generated by the public Tool builder. */
  readonly retry?: { readonly maxAttempts: number };
  /** Internal compatibility switch controlling whether an unknown effect suspends or fails Work. */
  readonly unknownEffect?: 'wait' | 'fail';
  /** Internal admission category used by layered execution limits. */
  readonly category?: 'model';
  /** Split by the operation executor around invocation so blocked input creates no Attempt. */
  readonly guardrails?: readonly Guardrail[];
  readonly invoke: (
    call: Readonly<{
      input: I;
      operationId: string;
      attemptId: string;
      signal: AbortSignal;
      progress?: (event: {
        type: string;
        text?: string;
        usage?: { inputTokens?: number; outputTokens?: number; totalTokens?: number };
      }) => void;
      /** Internal seam used by Agent-backed model turns for transient item delivery. */
      emitModelItem?: (item: ModelItem) => void;
    }>,
  ) => Promise<Outcome<O>>;
  readonly reconcile?: (
    call: Readonly<{ input: I; operationId: string; attemptId: string; signal: AbortSignal }>,
  ) => Promise<ReconciliationResult<O>>;
}
export interface Call {
  readonly id: string;
  readonly slot: string;
  readonly tool: Identity;
  readonly input: Json;
  readonly objectiveRevision: ObjectiveRevision;
  readonly status: 'planned' | 'admitted' | 'settled' | 'unknown' | 'withdrawn';
  readonly outcome: Outcome | null;
}
export type EffectResolution =
  | { readonly status: 'success'; readonly value: Json }
  | { readonly status: 'failure'; readonly effect: 'partial' | 'occurred'; readonly reason: Reason }
  | { readonly status: 'not-applied'; readonly reason: Reason };
export interface ResolveEffectRequest {
  readonly requestId: RequestId;
  readonly operationId: string;
  readonly resolution: EffectResolution;
}
export interface EffectResolutionAcceptance {
  readonly operationId: string;
  readonly attemptId: string;
  readonly action: 'settled' | 'retry-planned';
}
