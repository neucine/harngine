import type { Closure } from './work.js';
import type { Identity } from './types.js';
import type { InputPolicy } from './interaction.js';
import type { Outcome } from './operation.js';
import type { Policy } from './work.js';
import type { Json, Schema } from './types.js';

export type ContextSource =
  | ({ readonly type: 'work_context'; readonly index: number } & Json)
  | ({ readonly type: 'work_input'; readonly id: string } & Json)
  | ({ readonly type: 'work_call'; readonly id: string } & Json)
  | ({ readonly type: 'work_child'; readonly id: string } & Json)
  | ({ readonly type: 'reply'; readonly waitId: string } & Json);
export type ContextItem =
  | ({
      readonly type: 'input' | 'result' | 'output' | 'reference';
      readonly content: Json;
      readonly source: ContextSource;
    } & Json)
  | ({
      readonly type: 'tool_outcome';
      readonly call: {
        readonly id: string;
        readonly slot: string;
        readonly tool: { readonly id: string; readonly version: string } & Json;
        readonly input: Json;
      } & Json;
      readonly outcome: Outcome & Json;
      readonly source: ContextSource;
    } & Json)
  | ({
      readonly type: 'child_outcome';
      readonly call: {
        readonly id: string;
        readonly slot: string;
        readonly target: {
          readonly kind: 'agent' | 'workflow';
          readonly id: string;
          readonly version: string;
        };
        readonly objective: Json;
        readonly mode: 'sequential' | 'concurrent';
      } & Json;
      readonly closure: Closure & Json;
      readonly source: ContextSource;
    } & Json)
  | ({
      readonly type: 'reply';
      readonly question: string;
      readonly content: Json;
      readonly source: ContextSource;
    } & Json)
  | ({
      readonly type: 'summary';
      readonly content: Json;
      readonly sources: ContextSource[];
    } & Json);
export type AgentTool = {
  readonly id: string;
  readonly version: string;
  readonly description: string;
  readonly effect: 'read' | 'write';
  readonly inputSchema: Json;
  readonly outputSchema: Json;
} & Json;
export type ModelContext = {
  readonly instructions: string;
  readonly objective: Json;
  readonly turn: number;
  readonly tools: AgentTool[];
  readonly items: ContextItem[];
} & Json;
export interface AgentModel extends Identity {
  readonly artifactDigest: string;
  readonly invoke: (
    call: Readonly<{
      input: ModelContext;
      responseSchema: Json;
      ordinal: number;
      operationId: string;
      attemptId: string;
      signal: AbortSignal;
    }>,
  ) => Promise<Outcome<Json>>;
}
export interface Agent<O extends Json = Json, R extends Json = Json, I extends Json = Json>
  extends Identity {
  readonly artifactDigest: string;
  readonly instructions: string;
  readonly objective: Schema<O>;
  readonly result: Schema<R>;
  readonly input?: InputPolicy<I>;
  readonly model: Identity;
  /** Exact response contract generated by the Agent from its result and tools. */
  readonly modelResponse: Schema<Json>;
  readonly tools: readonly Identity[];
  readonly policy: Policy;
  readonly context: { readonly maxEntries: number };
  readonly reply?: {
    readonly schema: Schema;
    readonly responders: readonly string[];
    readonly timeoutMs?: number;
  };
}
export type AnyAgent = Agent<any, any, any>;
