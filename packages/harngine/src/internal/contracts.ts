export type ContextItem =
  | ({
      readonly type: 'input' | 'result' | 'output' | 'reference';
      readonly content: Json;
      readonly source: ContextSource;
    } & Json)
  | ({
      readonly type: 'tool_outcome';
      readonly call: {
        readonly id: string;
        readonly slot: string;
        readonly tool: { readonly id: string; readonly version: string } & Json;
        readonly input: Json;
      } & Json;
      readonly outcome: Outcome & Json;
      readonly source: ContextSource;
    } & Json)
  | ({
      readonly type: 'child_outcome';
      readonly call: {
        readonly id: string;
        readonly slot: string;
        readonly target: {
          readonly kind: 'agent' | 'workflow';
          readonly id: string;
          readonly version: string;
        };
        readonly objective: Json;
        readonly mode: 'sequential' | 'concurrent';
      } & Json;
      readonly closure: Closure & Json;
      readonly source: ContextSource;
    } & Json)
  | ({
      readonly type: 'reply';
      readonly question: string;
      readonly content: Json;
      readonly source: ContextSource;
    } & Json)
  | ({
      readonly type: 'summary';
      readonly content: Json;
      readonly sources: ContextSource[];
    } & Json);
