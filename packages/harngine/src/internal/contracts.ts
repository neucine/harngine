export type { Json, Schema, SessionId, WorkId } from '../types.js';
declare const brand: unique symbol;
export type RequestId = string & { readonly [brand]: 'RequestId' };
export type ControlToken = string & { readonly [brand]: 'ControlToken' };
export type ObjectiveRevision = number & { readonly [brand]: 'ObjectiveRevision' };
export type ProgressCursor = number & { readonly [brand]: 'ProgressCursor' };
export type Reason = Readonly<{ code: string; message: string }>;
export class RuntimeError extends Error {
  constructor(
    readonly code: string,
    message: string,
  ) {
    super(message);
    this.name = 'RuntimeError';
  }
}
export function requestId(value: string): RequestId {
  if (typeof value !== 'string' || !value || value.length > 256)
    throw new RuntimeError('INVALID_ID', 'Request identity must have 1–256 characters');
  return value as RequestId;
}
export interface Identity {
  readonly id: string;
  readonly version: string;
}
export interface Policy {
  readonly maxDecisions: number;
  readonly maxAttempts: number;
  readonly maxOperations?: number;
  readonly maxModelTurns?: number;
  readonly maxToolExecutions?: number;
  readonly maxChildWork?: number;
  readonly maxDepth?: number;
}
export type Outcome<O extends Json = Json> =
  | { status: 'success'; value: O }
  | { status: 'failure'; effect: 'none' | 'partial' | 'occurred'; reason: Reason }
  | { status: 'unknown'; reason: Reason };
export type ReconciliationResult<O extends Json = Json> =
  | { readonly status: 'success'; readonly value: O }
  | { readonly status: 'failure'; readonly effect: 'partial' | 'occurred'; readonly reason: Reason }
  | { readonly status: 'not-applied' | 'unknown'; readonly reason: Reason };
export type ToolCapabilities =
  | { readonly effect: 'read'; readonly invocation: 'repeatable' }
  | {
      readonly effect: 'write';
      readonly idempotency: 'none' | 'operation-key' | 'intrinsic';
      readonly reconciliation: 'manual' | 'automatic';
      readonly reversibility: 'unknown' | 'reversible' | 'irreversible';
    };
export interface Tool<I extends Json = Json, O extends Json = Json> extends Identity {
  readonly artifactDigest: string;
  readonly description?: string;
  readonly input: Schema<I>;
  readonly output: Schema<O>;
  readonly effect: 'read' | 'write';
  readonly capabilities?: ToolCapabilities;
  readonly approval?: ApprovalPolicy;
  /** Internal execution policy generated by the public Tool builder. */
  readonly retry?: { readonly maxAttempts: number };
  /** Internal compatibility switch controlling whether an unknown effect suspends or fails Work. */
  readonly unknownEffect?: 'wait' | 'fail';
  /** Internal admission category used by layered execution limits. */
  readonly category?: 'model';
  readonly invoke: (
    call: Readonly<{
      input: I;
      operationId: string;
      attemptId: string;
      signal: AbortSignal;
      progress?: (event: {
        type: string;
        text?: string;
        usage?: { inputTokens?: number; outputTokens?: number; totalTokens?: number };
      }) => void;
    }>,
  ) => Promise<Outcome<O>>;
  readonly reconcile?: (
    call: Readonly<{ input: I; operationId: string; attemptId: string; signal: AbortSignal }>,
  ) => Promise<ReconciliationResult<O>>;
}
